using System.Text.Json;
using System.Text.Json.Serialization;
using OpsFlow.Domain.Auditing;
using OpsFlow.Domain.Common;
using OpsFlow.Domain.Users;

namespace OpsFlow.Domain.Requests;

/// <summary>
/// Aggregate root for a purchase or expense request and its approval chain.
/// Every state change goes through a method here, which enforces the business rules in
/// docs/requirements.md and records an audit entry for the change.
/// </summary>
public sealed class Request
{
    public const int TitleMinLength = 3;
    public const int TitleMaxLength = 200;
    public const int DescriptionMaxLength = 4000;
    public const decimal MaxAmount = 1_000_000m;

    private static readonly JsonSerializerOptions AuditJsonOptions = new(JsonSerializerDefaults.Web)
    {
        Converters = { new JsonStringEnumConverter() },
    };

    private readonly List<ApprovalStep> _steps = [];
    private readonly List<AuditEntry> _auditEntries = [];

    private Request() { } // EF Core

    public long Id { get; private set; }

    /// <summary>Human-readable reference (e.g. <c>REQ-000042</c>), generated by the database from <see cref="Id"/>.</summary>
    public string Reference { get; private set; } = null!;

    public string Title { get; private set; } = null!;

    public string? Description { get; private set; }

    public RequestCategory Category { get; private set; }

    public decimal Amount { get; private set; }

    public RequestStatus Status { get; private set; }

    public int RequesterId { get; private set; }

    /// <summary>Approval round; 0 until first submitted, incremented on every (re)submission.</summary>
    public int CurrentRound { get; private set; }

    public DateTimeOffset CreatedAt { get; private set; }

    public DateTimeOffset UpdatedAt { get; private set; }

    public DateTimeOffset? SubmittedAt { get; private set; }

    public DateTimeOffset? CompletedAt { get; private set; }

    /// <summary>Concurrency token for the whole aggregate (exposed to clients as the ETag).</summary>
    public byte[] RowVersion { get; private set; } = [];

    /// <summary>Steps loaded with the request (handlers load the current round only).</summary>
    public IReadOnlyList<ApprovalStep> Steps => _steps;

    /// <summary>Audit entries added by operations on this instance; never loaded for commands.</summary>
    public IReadOnlyList<AuditEntry> AuditEntries => _auditEntries;

    public static Result<Request> Create(
        Actor requester,
        string title,
        string? description,
        RequestCategory category,
        decimal amount,
        DateTimeOffset now)
    {
        if (requester.Role == UserRole.Admin)
        {
            return RequestErrors.AdminCannotCreate;
        }

        var detailsError = ValidateDetails(title, description, amount);
        if (detailsError is not null)
        {
            return detailsError;
        }

        var request = new Request
        {
            Title = title.Trim(),
            Description = string.IsNullOrWhiteSpace(description) ? null : description.Trim(),
            Category = category,
            Amount = amount,
            Status = RequestStatus.Draft,
            RequesterId = requester.UserId,
            CreatedAt = now,
            UpdatedAt = now,
        };

        request.AddAudit(
            requester,
            AuditActions.RequestCreated,
            fromStatus: null,
            toStatus: RequestStatus.Draft,
            now,
            new { request.Title, request.Category, request.Amount });

        return request;
    }

    /// <summary>
    /// Submits the request for approval (BR-10..BR-12, BR-16): starts a new round whose steps are
    /// generated from <paramref name="policy"/>. The Manager step is assigned to the requester's manager.
    /// </summary>
    public Result Submit(Actor actor, int? requesterManagerId, ApprovalPolicy policy, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(policy);

        if (actor.UserId != RequesterId)
        {
            return RequestErrors.NotOwner;
        }

        if (Status is not (RequestStatus.Draft or RequestStatus.ChangesRequested))
        {
            return RequestErrors.InvalidTransition(Status, "submit");
        }

        if (requesterManagerId is null)
        {
            return RequestErrors.RequesterHasNoManager;
        }

        var previousStatus = Status;
        CurrentRound++;

        foreach (var template in policy.StepsFor(Amount))
        {
            var assigneeId = template.Kind == StepKind.Manager ? requesterManagerId : null;
            _steps.Add(new ApprovalStep(CurrentRound, template.StepOrder, template.Kind, assigneeId));
        }

        Status = RequestStatus.InApproval;
        SubmittedAt = now;
        UpdatedAt = now;

        AddAudit(
            actor,
            AuditActions.RequestSubmitted,
            previousStatus,
            Status,
            now,
            new
            {
                Round = CurrentRound,
                Steps = CurrentRoundSteps().Select(s => new { s.StepOrder, s.Kind, s.AssigneeId }),
            });

        return Result.Success();
    }

    public IEnumerable<ApprovalStep> CurrentRoundSteps() =>
        _steps.Where(s => s.Round == CurrentRound).OrderBy(s => s.StepOrder);

    private static DomainError? ValidateDetails(string title, string? description, decimal amount)
    {
        var trimmedTitle = title?.Trim() ?? string.Empty;
        if (trimmedTitle.Length is < TitleMinLength or > TitleMaxLength)
        {
            return RequestErrors.InvalidTitle;
        }

        if (description is { Length: > DescriptionMaxLength })
        {
            return RequestErrors.InvalidDescription;
        }

        if (amount <= 0 || amount > MaxAmount || decimal.Round(amount, 2) != amount)
        {
            return RequestErrors.InvalidAmount;
        }

        return null;
    }

    private void AddAudit(
        Actor actor,
        string action,
        RequestStatus? fromStatus,
        RequestStatus? toStatus,
        DateTimeOffset now,
        object? details)
    {
        var json = details is null ? null : JsonSerializer.Serialize(details, AuditJsonOptions);
        _auditEntries.Add(new AuditEntry(actor.UserId, action, fromStatus, toStatus, json, now));
    }
}
