using System.Text.Json;
using System.Text.Json.Serialization;
using OpsFlow.Domain.Auditing;
using OpsFlow.Domain.Common;
using OpsFlow.Domain.Users;

namespace OpsFlow.Domain.Requests;

/// <summary>
/// Aggregate root for a purchase or expense request and its approval chain.
/// Every state change goes through a method here, which enforces the business rules in
/// docs/requirements.md and records an audit entry for the change.
/// </summary>
public sealed class Request
{
    public const int TitleMinLength = 3;
    public const int TitleMaxLength = 200;
    public const int DescriptionMaxLength = 4000;
    public const decimal MaxAmount = 1_000_000m;

    private static readonly JsonSerializerOptions AuditJsonOptions = new(JsonSerializerDefaults.Web)
    {
        Converters = { new JsonStringEnumConverter() },
    };

    private readonly List<ApprovalStep> _steps = [];
    private readonly List<AuditEntry> _auditEntries = [];

    private Request() { } // EF Core

    public long Id { get; private set; }

    /// <summary>Human-readable reference (e.g. <c>REQ-000042</c>), generated by the database from <see cref="Id"/>.</summary>
    public string Reference { get; private set; } = null!;

    public string Title { get; private set; } = null!;

    public string? Description { get; private set; }

    public RequestCategory Category { get; private set; }

    public decimal Amount { get; private set; }

    public RequestStatus Status { get; private set; }

    public int RequesterId { get; private set; }

    /// <summary>Approval round; 0 until first submitted, incremented on every (re)submission.</summary>
    public int CurrentRound { get; private set; }

    public DateTimeOffset CreatedAt { get; private set; }

    public DateTimeOffset UpdatedAt { get; private set; }

    public DateTimeOffset? SubmittedAt { get; private set; }

    public DateTimeOffset? CompletedAt { get; private set; }

    /// <summary>Concurrency token for the whole aggregate (exposed to clients as the ETag).</summary>
    public byte[] RowVersion { get; private set; } = [];

    /// <summary>Steps loaded with the request (handlers load the current round only).</summary>
    public IReadOnlyList<ApprovalStep> Steps => _steps;

    /// <summary>Audit entries added by operations on this instance; never loaded for commands.</summary>
    public IReadOnlyList<AuditEntry> AuditEntries => _auditEntries;

    public static Result<Request> Create(
        Actor requester,
        string title,
        string? description,
        RequestCategory category,
        decimal amount,
        DateTimeOffset now)
    {
        if (requester.Role == UserRole.Admin)
        {
            return RequestErrors.AdminCannotCreate;
        }

        var detailsError = ValidateDetails(title, description, amount);
        if (detailsError is not null)
        {
            return detailsError;
        }

        var request = new Request
        {
            Title = title.Trim(),
            Description = string.IsNullOrWhiteSpace(description) ? null : description.Trim(),
            Category = category,
            Amount = amount,
            Status = RequestStatus.Draft,
            RequesterId = requester.UserId,
            CreatedAt = now,
            UpdatedAt = now,
        };

        request.AddAudit(
            requester,
            AuditActions.RequestCreated,
            fromStatus: null,
            toStatus: RequestStatus.Draft,
            now,
            new { request.Title, request.Category, request.Amount });

        return request;
    }

    /// <summary>
    /// Submits the request for approval (BR-10..BR-12, BR-16): starts a new round whose steps are
    /// generated from <paramref name="policy"/>. The Manager step is assigned to the requester's manager.
    /// </summary>
    /// <param name="requesterManager">The requester's manager if active, otherwise null (BR-12).</param>
    /// <param name="activeApprovers">Active Finance and Director users: a chain is only started if every
    /// step has someone who may decide it, so no request can get stuck in approval (BR-13a).</param>
    public Result Submit(
        Actor actor,
        Actor? requesterManager,
        ApprovalPolicy policy,
        IReadOnlyCollection<Actor> activeApprovers,
        DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(policy);
        ArgumentNullException.ThrowIfNull(activeApprovers);

        if (actor.UserId != RequesterId)
        {
            return RequestErrors.NotOwner;
        }

        if (Status is not (RequestStatus.Draft or RequestStatus.ChangesRequested))
        {
            return RequestErrors.InvalidTransition(Status, "submit");
        }

        if (requesterManager is not { } manager
            || manager.UserId == RequesterId
            || !ApprovalStep.IsEligibleRole(StepKind.Manager, manager.Role))
        {
            return RequestErrors.RequesterHasNoManager;
        }

        var templates = policy.StepsFor(Amount);

        // BR-20/BR-21: later steps need someone other than the requester and the manager (who decides step 1).
        foreach (var template in templates.Where(t => t.Kind != StepKind.Manager))
        {
            var hasDecider = activeApprovers.Any(a =>
                ApprovalStep.IsEligibleRole(template.Kind, a.Role) && a.UserId != RequesterId && a.UserId != manager.UserId);
            if (!hasDecider)
            {
                return RequestErrors.NoEligibleApprover(template.Kind);
            }
        }

        var previousStatus = Status;
        CurrentRound++;

        foreach (var template in templates)
        {
            var assigneeId = template.Kind == StepKind.Manager ? manager.UserId : (int?)null;
            _steps.Add(new ApprovalStep(CurrentRound, template.StepOrder, template.Kind, assigneeId));
        }

        Status = RequestStatus.InApproval;
        SubmittedAt = now;
        UpdatedAt = now;

        AddAudit(
            actor,
            AuditActions.RequestSubmitted,
            previousStatus,
            Status,
            now,
            new
            {
                Round = CurrentRound,
                Steps = CurrentRoundSteps().Select(s => new { s.StepOrder, s.Kind, s.AssigneeId }),
            });

        return Result.Success();
    }

    /// <summary>Edits the request details (BR-03). Only the requester, only before or between approval rounds.</summary>
    public Result Update(Actor actor, string title, string? description, RequestCategory category, decimal amount, DateTimeOffset now)
    {
        if (actor.UserId != RequesterId)
        {
            return RequestErrors.NotOwner;
        }

        if (Status is not (RequestStatus.Draft or RequestStatus.ChangesRequested))
        {
            return RequestErrors.InvalidTransition(Status, "edit");
        }

        var detailsError = ValidateDetails(title, description, amount);
        if (detailsError is not null)
        {
            return detailsError;
        }

        var before = new { Title, Category, Amount };
        Title = title.Trim();
        Description = string.IsNullOrWhiteSpace(description) ? null : description.Trim();
        Category = category;
        Amount = amount;
        UpdatedAt = now;

        AddAudit(actor, AuditActions.RequestUpdated, Status, Status, now, new { Before = before, After = new { Title, Category, Amount } });
        return Result.Success();
    }

    /// <summary>
    /// Records a decision on an approval step (BR-13..BR-15, BR-20, BR-21, BR-25). The current round's
    /// steps must be loaded. Rejecting or requesting changes ends the round and skips the remaining steps.
    /// </summary>
    public Result Decide(long stepId, Actor actor, Decision decision, string? comment, DateTimeOffset now)
    {
        if (Status != RequestStatus.InApproval)
        {
            return RequestErrors.InvalidTransition(Status, "decide on");
        }

        var roundSteps = CurrentRoundSteps().ToList();
        var step = roundSteps.SingleOrDefault(s => s.Id == stepId);
        if (step is null)
        {
            return ApprovalErrors.StepNotFound;
        }

        if (step.Status != StepStatus.Pending)
        {
            return ApprovalErrors.StepAlreadyDecided;
        }

        if (roundSteps.First(s => s.Status == StepStatus.Pending) != step)
        {
            return ApprovalErrors.StepNotCurrent;
        }

        if (actor.UserId == RequesterId)
        {
            return ApprovalErrors.SelfApproval;
        }

        var eligibilityError = step.AssigneeId is { } assigneeId
            ? (assigneeId == actor.UserId ? null : ApprovalErrors.NotAssignee)
            : (ApprovalStep.IsEligibleRole(step.Kind, actor.Role) ? null : ApprovalErrors.NotEligible);
        if (eligibilityError is not null)
        {
            return eligibilityError;
        }

        if (roundSteps.Any(s => s.DecidedById == actor.UserId))
        {
            return ApprovalErrors.DuplicateApprover;
        }

        var trimmedComment = string.IsNullOrWhiteSpace(comment) ? null : comment.Trim();
        if (trimmedComment is { Length: > ApprovalStep.CommentMaxLength })
        {
            return ApprovalErrors.CommentTooLong;
        }

        if (decision != Decision.Approve && trimmedComment is null)
        {
            return ApprovalErrors.CommentRequired;
        }

        var previousStatus = Status;
        var (stepOutcome, action) = decision switch
        {
            Decision.Approve => (StepStatus.Approved, AuditActions.StepApproved),
            Decision.Reject => (StepStatus.Rejected, AuditActions.StepRejected),
            Decision.RequestChanges => (StepStatus.ChangesRequested, AuditActions.ChangesRequested),
            _ => throw new ArgumentOutOfRangeException(nameof(decision), decision, "Unknown decision."),
        };

        step.RecordDecision(actor.UserId, stepOutcome, trimmedComment, now);

        switch (decision)
        {
            case Decision.Approve when roundSteps.All(s => s.Status == StepStatus.Approved):
                Status = RequestStatus.Approved;
                break;
            case Decision.Reject:
                SkipPendingSteps(roundSteps);
                Status = RequestStatus.Rejected;
                CompletedAt = now;
                break;
            case Decision.RequestChanges:
                SkipPendingSteps(roundSteps);
                Status = RequestStatus.ChangesRequested;
                break;
        }

        // Always touch the root so the aggregate's rowversion (the ETag) changes with every decision.
        UpdatedAt = now;

        AddAudit(
            actor,
            action,
            previousStatus,
            Status,
            now,
            new { StepId = step.Id, step.Round, step.StepOrder, step.Kind, Comment = trimmedComment });

        return Result.Success();
    }

    /// <summary>Assigns an unassigned pool step of the current round to the caller (BR-23).</summary>
    public Result ClaimStep(long stepId, Actor actor, DateTimeOffset now)
    {
        var (step, error) = FindPendingStep(stepId);
        if (step is null)
        {
            return error!;
        }

        if (step.AssigneeId is not null)
        {
            return ApprovalErrors.StepAlreadyAssigned;
        }

        if (actor.UserId == RequesterId)
        {
            return ApprovalErrors.SelfApproval;
        }

        if (!ApprovalStep.IsEligibleRole(step.Kind, actor.Role))
        {
            return ApprovalErrors.NotEligible;
        }

        if (CurrentRoundSteps().Any(s => s.DecidedById == actor.UserId))
        {
            return ApprovalErrors.DuplicateApprover;
        }

        step.AssignTo(actor.UserId);
        UpdatedAt = now;
        AddAudit(actor, AuditActions.StepClaimed, Status, Status, now, new { StepId = step.Id, step.Round, step.StepOrder, step.Kind });
        return Result.Success();
    }

    /// <summary>
    /// An administrator moves a pending step to another eligible, active user (BR-24), e.g. when the
    /// assignee is absent. Segregation of duties still applies to the new assignee.
    /// </summary>
    public Result ReassignStep(long stepId, Actor admin, Actor newAssignee, bool newAssigneeIsActive, DateTimeOffset now)
    {
        if (admin.Role != UserRole.Admin)
        {
            return ApprovalErrors.ReassignNotAllowed;
        }

        var (step, error) = FindPendingStep(stepId);
        if (step is null)
        {
            return error!;
        }

        var cannotAssign = !newAssigneeIsActive
            || !ApprovalStep.IsEligibleRole(step.Kind, newAssignee.Role)
            || newAssignee.UserId == RequesterId
            || CurrentRoundSteps().Any(s => s.DecidedById == newAssignee.UserId);
        if (cannotAssign)
        {
            return ApprovalErrors.AssigneeNotEligible;
        }

        var previousAssigneeId = step.AssigneeId;
        step.AssignTo(newAssignee.UserId);
        UpdatedAt = now;
        AddAudit(
            admin,
            AuditActions.StepReassigned,
            Status,
            Status,
            now,
            new { StepId = step.Id, step.Round, step.StepOrder, step.Kind, FromAssigneeId = previousAssigneeId, ToAssigneeId = newAssignee.UserId });
        return Result.Success();
    }

    /// <summary>The requester withdraws the request (BR-04, BR-17). The current round's steps must be loaded.</summary>
    public Result Cancel(Actor actor, DateTimeOffset now)
    {
        if (actor.UserId != RequesterId)
        {
            return RequestErrors.NotOwner;
        }

        if (Status is not (RequestStatus.Draft or RequestStatus.InApproval or RequestStatus.ChangesRequested))
        {
            return RequestErrors.InvalidTransition(Status, "cancel");
        }

        var previousStatus = Status;
        SkipPendingSteps(CurrentRoundSteps());
        Status = RequestStatus.Cancelled;
        CompletedAt = now;
        UpdatedAt = now;
        AddAudit(actor, AuditActions.RequestCancelled, previousStatus, Status, now, details: null);
        return Result.Success();
    }

    /// <summary>Finance records that an approved request was fulfilled (BR-30, BR-31).</summary>
    public Result Fulfil(Actor actor, DateTimeOffset now)
    {
        if (actor.Role != UserRole.Finance)
        {
            return RequestErrors.FulfilNotAllowed;
        }

        if (actor.UserId == RequesterId)
        {
            return RequestErrors.SelfFulfilment;
        }

        if (Status != RequestStatus.Approved)
        {
            return RequestErrors.InvalidTransition(Status, "fulfil");
        }

        Status = RequestStatus.Fulfilled;
        CompletedAt = now;
        UpdatedAt = now;
        AddAudit(actor, AuditActions.RequestFulfilled, RequestStatus.Approved, Status, now, details: null);
        return Result.Success();
    }

    public IEnumerable<ApprovalStep> CurrentRoundSteps() =>
        _steps.Where(s => s.Round == CurrentRound).OrderBy(s => s.StepOrder);

    private (ApprovalStep? Step, DomainError? Error) FindPendingStep(long stepId)
    {
        if (Status != RequestStatus.InApproval)
        {
            return (null, RequestErrors.InvalidTransition(Status, "change the approval steps of"));
        }

        var step = CurrentRoundSteps().SingleOrDefault(s => s.Id == stepId);
        if (step is null)
        {
            return (null, ApprovalErrors.StepNotFound);
        }

        return step.Status == StepStatus.Pending ? (step, null) : (null, ApprovalErrors.StepAlreadyDecided);
    }

    private static void SkipPendingSteps(IEnumerable<ApprovalStep> steps)
    {
        foreach (var pending in steps.Where(s => s.Status == StepStatus.Pending))
        {
            pending.Skip();
        }
    }

    private static DomainError? ValidateDetails(string title, string? description, decimal amount)
    {
        var trimmedTitle = title?.Trim() ?? string.Empty;
        if (trimmedTitle.Length is < TitleMinLength or > TitleMaxLength)
        {
            return RequestErrors.InvalidTitle;
        }

        if (description is { Length: > DescriptionMaxLength })
        {
            return RequestErrors.InvalidDescription;
        }

        if (amount <= 0 || amount > MaxAmount || decimal.Round(amount, 2) != amount)
        {
            return RequestErrors.InvalidAmount;
        }

        return null;
    }

    private void AddAudit(
        Actor actor,
        string action,
        RequestStatus? fromStatus,
        RequestStatus? toStatus,
        DateTimeOffset now,
        object? details)
    {
        var json = details is null ? null : JsonSerializer.Serialize(details, AuditJsonOptions);
        _auditEntries.Add(new AuditEntry(actor.UserId, action, fromStatus, toStatus, json, now));
    }
}
